-- 20261007180000_anomaly_service.sql — server anomaly models (TimesFM 3.0 forecast + UniTS reconstruction).
--
-- Additive only. Written by the `frwhoop-anomaly` service on the VPS (Tools/AnomalyService), read by the phone
-- through the `scores/anomaly-candidates` route. Model output is a CANDIDATE: the phone's verification stage
-- (WatchdogVerifier.swift) decides whether anything alerts. Nothing here notifies.
--
-- Hazards honoured (docs/BASELINE_WATCHDOG_V2.md §5):
--   • no trigger on noop_* tables and no use of the scoring-inputs-v2 advisory lock (uploads hold it
--     exclusively; lock_timeout 8 s turns any contention into push 500s);
--   • jobs are discovered from scoring_jobs_v2 completions (raw data has landed), throttled per owner;
--   • a stale worker can never overwrite a newer result (lease + revision fence on publish).

begin;

-- ---------------------------------------------------------------------------------------------------------
-- Queue: one job per (user, device). input_revision bumps when new scored data exist; watermark_ts is the end
-- of the newest minute the service has already scored (exclusive).
create table if not exists public.anomaly_jobs (
  user_id uuid not null references auth.users(id) on delete cascade,
  device_id uuid not null,
  input_revision bigint not null default 1 check (input_revision >= 1),
  completed_revision bigint not null default 0 check (completed_revision >= 0),
  lease_token uuid,
  lease_until timestamptz,
  consecutive_failures integer not null default 0 check (consecutive_failures >= 0),
  dead_letter boolean not null default false,
  not_before timestamptz not null default clock_timestamp(),
  dirty_at timestamptz not null default clock_timestamp(),
  watermark_ts timestamptz,
  last_claimed_at timestamptz,
  last_completed_at timestamptz,
  last_duration_ms bigint,
  last_error text,
  last_worker text,
  claim_count bigint not null default 0,
  success_count bigint not null default 0,
  renewal_count bigint not null default 0,
  lease_expiry_count bigint not null default 0,
  primary key (user_id, device_id),
  check ((lease_token is null) = (lease_until is null)),
  check (completed_revision <= input_revision),
  foreign key (user_id, device_id) references public.devices(user_id, id) on delete cascade
);
create index if not exists anomaly_jobs_due on public.anomaly_jobs (not_before)
  where completed_revision < input_revision and not dead_letter;
create unique index if not exists anomaly_jobs_token on public.anomaly_jobs (lease_token) where lease_token is not null;

-- ---------------------------------------------------------------------------------------------------------
-- Candidates: one row per anomaly window. candidate_key is deterministic (detector, channel group, window start)
-- so a re-score updates in place; result_revision is a monotone change cursor for the phone.
create sequence if not exists public.anomaly_result_revision_seq;

create table if not exists public.anomaly_candidates (
  candidate_id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  device_id uuid not null,
  candidate_key text not null check (candidate_key ~ '^[A-Za-z0-9._:-]{1,160}$'),
  start_ts timestamptz not null,
  end_ts timestamptz not null,
  local_day date not null,
  channels text[] not null check (cardinality(channels) between 1 and 8),
  -- Models whose calibrated p crossed their own threshold ('timesfm-3.0', 'units-x128').
  flagged_by text[] not null default '{}'::text[],
  -- {model id: calibrated two-sided p of the window}
  model_p jsonb not null default '{}'::jsonb,
  score double precision not null,
  severity text not null check (severity in ('candidate','strong')),
  direction smallint not null check (direction in (-1, 0, 1)),
  expected jsonb not null default '{}'::jsonb,
  observed jsonb not null default '{}'::jsonb,
  context jsonb not null default '{}'::jsonb,
  quality jsonb not null default '{}'::jsonb,
  model_versions jsonb not null default '{}'::jsonb,
  status text not null default 'candidate' check (status in ('candidate','suppressed','retracted')),
  suppressed_reason text,
  input_fingerprint text,
  result_revision bigint not null default nextval('public.anomaly_result_revision_seq'),
  computed_at timestamptz not null default clock_timestamp(),
  unique (user_id, device_id, candidate_key),
  check (end_ts > start_ts),
  foreign key (user_id, device_id) references public.devices(user_id, id) on delete cascade
);
create index if not exists anomaly_candidates_cursor on public.anomaly_candidates (user_id, device_id, result_revision);
create index if not exists anomaly_candidates_time on public.anomaly_candidates (user_id, device_id, start_ts desc);

-- Per-window, per-model scores for EVERY scored window (not only candidates): calibration, monitoring and the
-- model-contribution analysis. Kept 30 days (pruned by the service).
create table if not exists public.anomaly_window_scores (
  user_id uuid not null references auth.users(id) on delete cascade,
  device_id uuid not null,
  window_start timestamptz not null,
  window_end timestamptz not null,
  channel_group text not null,
  model text not null,
  score double precision,
  p double precision check (p is null or (p >= 0 and p <= 1)),
  context_kind text,
  usable boolean not null,
  withheld_reason text,
  computed_at timestamptz not null default clock_timestamp(),
  primary key (user_id, device_id, window_start, channel_group, model),
  foreign key (user_id, device_id) references public.devices(user_id, id) on delete cascade
);

create table if not exists public.anomaly_service_heartbeats (
  service_name text primary key check (service_name ~ '^[a-z0-9._-]{1,64}$'),
  beat_at timestamptz not null default clock_timestamp(),
  started_at timestamptz,
  source_revision text,
  models jsonb not null default '{}'::jsonb,
  counters jsonb not null default '{}'::jsonb,
  queue_due integer,
  oldest_due_age_s integer,
  last_error text
);

do $$
declare t text;
begin
  foreach t in array array['anomaly_jobs','anomaly_candidates','anomaly_window_scores','anomaly_service_heartbeats'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('revoke all on public.%I from public, anon, authenticated', t);
    execute format('grant all on public.%I to service_role', t);
    execute format('drop policy if exists anomaly_service on public.%I', t);
    execute format('create policy anomaly_service on public.%I for all to service_role using (true) with check (true)', t);
  end loop;
  -- The owner may read their own candidates (the phone reads through the scores route; this is defence in depth).
  grant select on public.anomaly_candidates to authenticated;
  drop policy if exists anomaly_candidates_select_own on public.anomaly_candidates;
  create policy anomaly_candidates_select_own on public.anomaly_candidates for select to authenticated
    using ((select auth.uid()) = user_id);
end $$;
grant usage, select on sequence public.anomaly_result_revision_seq to service_role;

-- ---------------------------------------------------------------------------------------------------------
-- Enqueue: a (user, device) is due when one of its last two days finished server scoring after the job was last
-- marked, at most once per p_min_interval per job. Never touches noop_* or the scoring lock.
create or replace function public.enqueue_anomaly_jobs_v1(p_limit integer default 50,
                                                         p_min_interval interval default interval '10 minutes')
returns integer language plpgsql security definer set search_path = '' as $$
declare n integer := 0; r record;
begin
  if p_limit is null or p_limit < 1 or p_limit > 1000 then raise exception 'invalid_limit' using errcode = '22023'; end if;
  for r in
    select s.user_id, s.device_id, max(s.last_completed_at) as touched
      from public.scoring_jobs_v2 s
     where s.algorithm_version = 'frwhoop-server-1' and s.completed_revision > 0
       and s.day >= (pg_catalog.now() at time zone 'UTC')::date - 2
       and s.last_completed_at is not null
       and not exists (select 1 from public.noop_account_retirements x where x.user_id = s.user_id)
       and exists (select 1 from public.devices d where d.id = s.device_id and d.user_id = s.user_id)
     group by s.user_id, s.device_id
     order by max(s.last_completed_at) desc
  loop
    exit when n >= p_limit;
    insert into public.anomaly_jobs as j (user_id, device_id, dirty_at)
    values (r.user_id, r.device_id, r.touched)
    on conflict (user_id, device_id) do update
      set input_revision = case when j.completed_revision >= j.input_revision then j.input_revision + 1 else j.input_revision end,
          dirty_at = excluded.dirty_at,
          not_before = greatest(j.not_before, coalesce(j.last_completed_at, '-infinity'::timestamptz) + p_min_interval)
      where excluded.dirty_at > j.dirty_at
        and (j.last_completed_at is null or j.last_completed_at <= pg_catalog.clock_timestamp() - p_min_interval);
    if found then n := n + 1; end if;
  end loop;
  return n;
end $$;

create or replace function public.claim_anomaly_job_v1(p_lease_seconds integer default 600)
returns setof public.anomaly_jobs language plpgsql security definer set search_path = '' as $$
declare j public.anomaly_jobs;
begin
  if p_lease_seconds < 1 or p_lease_seconds > 3600 then raise exception 'invalid_lease'; end if;
  select q.* into j from public.anomaly_jobs q
   where q.completed_revision < q.input_revision and not q.dead_letter and q.not_before <= clock_timestamp()
     and (q.lease_until is null or q.lease_until <= clock_timestamp())
   order by q.last_claimed_at nulls first, q.dirty_at
   for update of q skip locked limit 1;
  if not found then return; end if;
  return query update public.anomaly_jobs q set lease_token = gen_random_uuid(),
      lease_until = clock_timestamp() + make_interval(secs => p_lease_seconds),
      last_claimed_at = clock_timestamp(), claim_count = q.claim_count + 1,
      lease_expiry_count = q.lease_expiry_count + case when q.lease_token is null then 0 else 1 end
   where q.user_id = j.user_id and q.device_id = j.device_id
   returning q.*;
end $$;

create or replace function public.renew_anomaly_job_v1(p_token uuid, p_seconds integer default 600)
returns boolean language plpgsql security definer set search_path = '' as $$
begin
  if p_seconds < 1 or p_seconds > 3600 then raise exception 'invalid_lease'; end if;
  update public.anomaly_jobs set lease_until = clock_timestamp() + make_interval(secs => p_seconds),
         renewal_count = renewal_count + 1
   where lease_token = p_token and lease_until > clock_timestamp();
  return found;
end $$;

create or replace function public.fail_anomaly_job_v1(p_token uuid, p_revision bigint, p_error text)
returns void language plpgsql security definer set search_path = '' as $$
begin
  update public.anomaly_jobs set
    consecutive_failures = case when input_revision = p_revision then consecutive_failures + 1 else 0 end,
    dead_letter = (input_revision = p_revision and consecutive_failures + 1 >= 8),
    not_before = case when input_revision = p_revision then clock_timestamp() +
      make_interval(secs => least(3600, 30 * power(2, least(consecutive_failures, 7)))::integer)
      else clock_timestamp() end,
    last_error = left(p_error, 2000),
    lease_token = null, lease_until = null
   where lease_token = p_token and lease_until > clock_timestamp();
end $$;

-- Fenced publish. Payload:
-- {"scored_from": ts, "scored_to": ts, "worker": text, "run_ms": int,
--  "candidates": [{candidate_key, start_ts, end_ts, local_day, channels[], flagged_by[], model_p{}, score,
--                  severity, direction, expected{}, observed{}, context{}, quality{}, model_versions{},
--                  status, suppressed_reason, input_fingerprint}],
--  "window_scores": [{window_start, window_end, channel_group, model, score, p, context_kind, usable,
--                     withheld_reason}]}
-- Candidates of this (user, device) whose window starts inside [scored_from, scored_to) and that the new result
-- does not contain are marked 'retracted' (a re-score can withdraw a candidate; it is never silently deleted).
create or replace function public.publish_anomaly_result_v1(p_token uuid, p_revision bigint, p_payload jsonb)
returns bigint language plpgsql security definer set search_path = '' as $$
declare j public.anomaly_jobs; c jsonb; w jsonb; v_from timestamptz; v_to timestamptz; keys text[] := '{}'; n bigint := 0;
begin
  select * into j from public.anomaly_jobs where lease_token = p_token for update;
  if not found or j.lease_until <= clock_timestamp() or j.input_revision <> p_revision then return null; end if;
  if jsonb_typeof(p_payload) is distinct from 'object'
     or jsonb_typeof(p_payload -> 'candidates') is distinct from 'array'
     or jsonb_typeof(p_payload -> 'window_scores') is distinct from 'array' then
    raise exception 'invalid_anomaly_payload';
  end if;
  if octet_length(p_payload::text) > 4194304 then raise exception 'invalid_anomaly_size'; end if;
  v_from := (p_payload ->> 'scored_from')::timestamptz;
  v_to := (p_payload ->> 'scored_to')::timestamptz;
  if v_from is null or v_to is null or v_to <= v_from then raise exception 'invalid_anomaly_range'; end if;

  for c in select * from jsonb_array_elements(p_payload -> 'candidates') loop
    keys := keys || (c ->> 'candidate_key');
    insert into public.anomaly_candidates as a (user_id, device_id, candidate_key, start_ts, end_ts, local_day, channels,
        flagged_by, model_p, score, severity, direction, expected, observed, context, quality, model_versions,
        status, suppressed_reason, input_fingerprint)
    values (j.user_id, j.device_id, c ->> 'candidate_key', (c ->> 'start_ts')::timestamptz, (c ->> 'end_ts')::timestamptz,
        (c ->> 'local_day')::date,
        array(select jsonb_array_elements_text(c -> 'channels')),
        coalesce(array(select jsonb_array_elements_text(c -> 'flagged_by')), '{}'::text[]),
        coalesce(c -> 'model_p', '{}'::jsonb), (c ->> 'score')::double precision, c ->> 'severity',
        (c ->> 'direction')::smallint, coalesce(c -> 'expected', '{}'::jsonb), coalesce(c -> 'observed', '{}'::jsonb),
        coalesce(c -> 'context', '{}'::jsonb), coalesce(c -> 'quality', '{}'::jsonb),
        coalesce(c -> 'model_versions', '{}'::jsonb), coalesce(c ->> 'status', 'candidate'),
        c ->> 'suppressed_reason', c ->> 'input_fingerprint')
    on conflict (user_id, device_id, candidate_key) do update set
        start_ts = excluded.start_ts, end_ts = excluded.end_ts, local_day = excluded.local_day,
        channels = excluded.channels, flagged_by = excluded.flagged_by, model_p = excluded.model_p,
        score = excluded.score, severity = excluded.severity, direction = excluded.direction,
        expected = excluded.expected, observed = excluded.observed, context = excluded.context,
        quality = excluded.quality, model_versions = excluded.model_versions, status = excluded.status,
        suppressed_reason = excluded.suppressed_reason, input_fingerprint = excluded.input_fingerprint,
        result_revision = nextval('public.anomaly_result_revision_seq'), computed_at = clock_timestamp()
      where (a.score, a.status, a.end_ts, a.flagged_by, a.channels)
            is distinct from (excluded.score, excluded.status, excluded.end_ts, excluded.flagged_by, excluded.channels);
    n := n + 1;
  end loop;

  update public.anomaly_candidates a set status = 'retracted', suppressed_reason = 'not_in_rescore',
         result_revision = nextval('public.anomaly_result_revision_seq'), computed_at = clock_timestamp()
   where a.user_id = j.user_id and a.device_id = j.device_id and a.status <> 'retracted'
     and a.start_ts >= v_from and a.start_ts < v_to and not (a.candidate_key = any(keys));

  for w in select * from jsonb_array_elements(p_payload -> 'window_scores') loop
    insert into public.anomaly_window_scores as s (user_id, device_id, window_start, window_end, channel_group, model,
        score, p, context_kind, usable, withheld_reason)
    values (j.user_id, j.device_id, (w ->> 'window_start')::timestamptz, (w ->> 'window_end')::timestamptz,
        w ->> 'channel_group', w ->> 'model', (w ->> 'score')::double precision, (w ->> 'p')::double precision,
        w ->> 'context_kind', coalesce((w ->> 'usable')::boolean, false), w ->> 'withheld_reason')
    on conflict (user_id, device_id, window_start, channel_group, model) do update set
        window_end = excluded.window_end, score = excluded.score, p = excluded.p, context_kind = excluded.context_kind,
        usable = excluded.usable, withheld_reason = excluded.withheld_reason, computed_at = clock_timestamp();
  end loop;

  update public.anomaly_jobs set completed_revision = p_revision, lease_token = null, lease_until = null,
         consecutive_failures = 0, last_completed_at = clock_timestamp(), last_error = null,
         last_duration_ms = (p_payload ->> 'run_ms')::bigint, last_worker = left(p_payload ->> 'worker', 120),
         success_count = success_count + 1, watermark_ts = greatest(coalesce(watermark_ts, v_to), v_to)
   where user_id = j.user_id and device_id = j.device_id;
  return n;
end $$;

create or replace function public.anomaly_service_heartbeat_v1(p_name text, p_payload jsonb)
returns void language plpgsql security definer set search_path = '' as $$
declare v_due integer; v_age integer;
begin
  select count(*), coalesce(extract(epoch from (clock_timestamp() - min(not_before)))::integer, 0)
    into v_due, v_age
    from public.anomaly_jobs where completed_revision < input_revision and not dead_letter and not_before <= clock_timestamp();
  insert into public.anomaly_service_heartbeats as h (service_name, beat_at, started_at, source_revision, models, counters,
      queue_due, oldest_due_age_s, last_error)
  values (p_name, clock_timestamp(), (p_payload ->> 'started_at')::timestamptz, p_payload ->> 'source_revision',
      coalesce(p_payload -> 'models', '{}'::jsonb), coalesce(p_payload -> 'counters', '{}'::jsonb), v_due, v_age,
      p_payload ->> 'last_error')
  on conflict (service_name) do update set beat_at = excluded.beat_at, started_at = excluded.started_at,
      source_revision = excluded.source_revision, models = excluded.models, counters = excluded.counters,
      queue_due = excluded.queue_due, oldest_due_age_s = excluded.oldest_due_age_s, last_error = excluded.last_error;
end $$;

create or replace function public.prune_anomaly_window_scores_v1(p_keep interval default interval '30 days')
returns bigint language plpgsql security definer set search_path = '' as $$
declare n bigint;
begin
  delete from public.anomaly_window_scores where window_start < clock_timestamp() - p_keep;
  get diagnostics n = row_count;
  return n;
end $$;

do $$
declare f text;
begin
  foreach f in array array[
    'public.enqueue_anomaly_jobs_v1(integer, interval)',
    'public.claim_anomaly_job_v1(integer)',
    'public.renew_anomaly_job_v1(uuid, integer)',
    'public.fail_anomaly_job_v1(uuid, bigint, text)',
    'public.publish_anomaly_result_v1(uuid, bigint, jsonb)',
    'public.anomaly_service_heartbeat_v1(text, jsonb)',
    'public.prune_anomaly_window_scores_v1(interval)'] loop
    execute format('revoke all on function %s from public, anon, authenticated', f);
    execute format('grant execute on function %s to service_role', f);
  end loop;
end $$;

commit;
